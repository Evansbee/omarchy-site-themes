#!/usr/bin/env node

// Generates extension/sites/facebook.css from Facebook's dark-mode tokens.
// Facebook colors everything through custom properties declared on
// .__fb-dark-mode / .__fb-light-mode, so remapping them recolors the site.
//
// Input is a dump of the dark-mode token block, one "name: value" per line.
// Produce it from the devtools console on facebook.com:
//
//   copy([...document.styleSheets].flatMap(s => { try { return [...s.cssRules] } catch { return [] } })
//     .find(r => /\.__fb-dark-mode/.test(r.selectorText || ""))
//     .style.cssText.split(";").join("\n"))
//
// then save the clipboard to a file and run: tools/gen-facebook.js tokens.txt

const fs = require("fs");
const path = require("path");
const P = require("../extension/palette.js");

const OUT = path.join(__dirname, "../extension/sites/facebook.css");

const HUE_HINTS = [
  [/negative|critical|destructive|cherry|tomato|red|rose|notification-badge|event-date/i, "red"],
  [/positive|success|lime|green|chartreuse/i, "green"],
  [/warning|attention|lemon|yellow|rating-star/i, "yellow"],
  [/orange|hero-banner/i, "orange"],
  [/grape|purple|pink|fuschia|magenta|violet|pending/i, "magenta"],
  [/teal|seafoam|cyan/i, "cyan"],
  [/blue|link|primary-button|focus|^--accent$|switch-active|selected|highlight|slider|toggle-on|progress-ring-default|informational/i, "accent"],
];

// Left alone: overlays on photos and video, and the logo.
const SKIP = /always-|on-media|on-light-media|fb-logo|shadow|dataviz|data-viz|scroll-shadow|glimmer-base|blur-.*-(dark|light)$/i;

function role(name) {
  if (/^--(negative|positive|warning|event-date)$/.test(name)) return "fg";
  if (/text|icon|wordmark|link|chevron|star|placeholder-text|section-header|^--accent$|glimmer|dot-|stepper/i.test(name)) return "fg";
  if (/border|divider|stroke|ring/i.test(name)) return "border";
  return "bg";
}

function hint(name) {
  if (/^--(primary-button|primary-destructive-button|toggle-active)-(text|icon)$|inverse-text|primary-deemphasized-button-text/i.test(name)) {
    return { expr: "var(--om-fg-strong)" };
  }
  for (const [re, hue] of HUE_HINTS) if (re.test(name)) return { hue };
  return {};
}

const lines = fs.readFileSync(process.argv[2], "utf8").split(/\n/)
  .map((l) => l.trim().match(/^(--[\w-]+):\s*(.+?);?$/)).filter(Boolean)
  .map((m) => [m[1], m[2]]);
const get = (n) => P.colorsIn(lines.find(([k]) => k === n)[1])[0];
const ctx = { bgL: P.lightness(get("--web-wash")), fgL: P.lightness(get("--primary-text")) };

const out = [];
for (const [name, value] of lines) {
  if (SKIP.test(name)) continue;
  const mapped = P.remapValue(value, role(name), ctx, hint(name));
  if (mapped) out.push(`  ${name}: ${mapped} !important;`);
}

fs.writeFileSync(OUT, `/* Facebook: generated by tools/gen-facebook.js from the dark-mode tokens.
   Do not edit by hand. */

html[data-omarchy-themed],
html[data-omarchy-themed] :is(.__fb-dark-mode, .__fb-light-mode) {
${out.join("\n")}
}

html[data-omarchy-themed] body {
  background-color: var(--om-bg) !important;
}
`);
console.log(`${out.length} tokens -> ${path.relative(process.cwd(), OUT)}`);
